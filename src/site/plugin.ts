/// <reference types="node" />
// Vite plugin that turns src/site into deployable files. At build time it
// fills the home page's static first paint and JSON-LD from content.ts, and
// emits the information pages, their Markdown twins, llms.txt, the sitemap,
// and the Cloudflare Pages _headers and _routes.json.

import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { Plugin } from 'vite';
import { THEMES } from '../ui/theme.ts';
import { KEYS } from '../ui/storage.ts';
import { HOME, NOT_FOUND, PAGES } from './content.ts';
import { SECURITY_HEADERS } from './config.ts';
import {
  homeShellHtml,
  jsonLdScript,
  llmsTxt,
  pageDocument,
  pageMarkdown,
  sitemapXml,
} from './render.ts';

const PAGES_CSS = fileURLToPath(new URL('./pages.css', import.meta.url));

/** Files the PWA plugin writes at the dist root after our hooks run. */
const PWA_FILES = ['sw.js', 'registerSW.js', 'manifest.webmanifest'];

function themeCss(): string {
  return THEMES.map((theme, i) => {
    const selector = i === 0 ? ':root' : `:root[data-theme='${theme.id}']`;
    const vars = Object.entries(theme.vars)
      .map(([k, v]) => `  ${k}: ${v};`)
      .join('\n');
    return `${selector} {\n${vars}\n}`;
  }).join('\n\n');
}

/** Applies the player's saved theme before first paint on the static pages. */
function themeJs(): string {
  return `try{var t=JSON.parse(localStorage.getItem(${JSON.stringify(KEYS.prefs)})||'{}').theme;if(t)document.documentElement.dataset.theme=t}catch(e){}\n`;
}

function headersFile(): string {
  const block = (pattern: string, headers: Record<string, string>) =>
    [pattern, ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`)].join(
      '\n'
    );
  const markdownTwins = [...PAGES, NOT_FOUND].map((p) =>
    block(p.mdPath, { 'Content-Type': 'text/markdown; charset=utf-8' })
  );
  return (
    [
      '# Generated by src/site/plugin.ts. Edit there, not here.',
      block('/*', SECURITY_HEADERS),
      block('/assets/*', {
        'Cache-Control': 'public, max-age=31536000, immutable',
      }),
      ...markdownTwins,
      block('/llms.txt', { 'Content-Type': 'text/plain; charset=utf-8' }),
    ].join('\n\n') + '\n'
  );
}

/**
 * Pages Function routing: run the middleware for page routes and unknown
 * paths only. Every real static file except HTML is excluded so asset
 * requests never invoke (or get billed as) a Function.
 */
export function routesJson(staticFiles: string[]): string {
  const exclude = [
    '/assets/*',
    ...staticFiles
      .filter((f) => !f.endsWith('.html') && !f.startsWith('_'))
      .map((f) => `/${f}`),
  ];
  return JSON.stringify({ version: 1, include: ['/*'], exclude }, null, 2);
}

/** Every generated file, keyed by its path in dist/. */
export function siteFiles(publicFiles: string[] = []): Record<string, string> {
  const files: Record<string, string> = {
    'site.css': themeCss() + '\n\n' + readFileSync(PAGES_CSS, 'utf8'),
    'theme.js': themeJs(),
    'llms.txt': llmsTxt(),
    'sitemap.xml': sitemapXml(),
    _headers: headersFile(),
  };
  for (const page of [...PAGES, NOT_FOUND]) {
    files[page.mdPath.slice(1)] = pageMarkdown(page);
    if (page.htmlFile) files[page.htmlFile] = pageDocument(page);
  }
  const rootFiles = [
    ...new Set([...publicFiles, ...Object.keys(files), ...PWA_FILES]),
  ].sort();
  files['_routes.json'] = routesJson(rootFiles);
  return files;
}

/**
 * The app writes its theme variables at boot. Until then (and forever, for
 * visitors and crawlers without JavaScript) the default Daylight palette is
 * inlined so the static first paint is styled, not browser defaults.
 */
function defaultThemeStyle(): string {
  const vars = Object.entries(THEMES[0]!.vars)
    .map(([k, v]) => `${k}: ${v};`)
    .join(' ');
  return `<style>:root { ${vars} }</style>`;
}

export function siteHtml(indexHtml: string): string {
  return indexHtml
    .replace('<!--site:home-->', homeShellHtml(HOME))
    .replace(
      '<!--site:jsonld-->',
      jsonLdScript(HOME) + '\n' + defaultThemeStyle()
    );
}

export function countLudoSite(): Plugin {
  let publicDir = '';
  return {
    name: 'count-ludo-site',
    configResolved(config) {
      publicDir = config.publicDir;
    },
    transformIndexHtml: {
      order: 'pre',
      handler: siteHtml,
    },
    generateBundle() {
      const publicFiles = publicDir ? readdirSync(publicDir) : [];
      for (const [fileName, source] of Object.entries(siteFiles(publicFiles))) {
        this.emitFile({ type: 'asset', fileName, source });
      }
    },
  };
}
